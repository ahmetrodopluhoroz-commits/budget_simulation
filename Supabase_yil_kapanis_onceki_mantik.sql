-- Yıl Kapanış (Önceki Mantık) sonucunu revizyon bazında saklar.
-- Operasyon desi raporundaki kapanan yıl (ör. 2026) sütunları bu tablodan
-- alınır. Supabase > SQL Editor'de bir kez çalıştırmanız yeterlidir.

create table if not exists public.yil_kapanis_onceki_detay_tablosu (
    id bigint generated by default as identity primary key,
    revizyon_id text not null,
    "Uniq ID" text not null,
    "Yıl" bigint not null,
    "Teslimat Tipi" text,
    "Atf Tipi" text,
    "Çıkış İl Adı" text,
    "Çıkış Şube Adı" text,
    "Varış İl Adı" text,
    "Varış Şube Adı" text,
    "İlk Okutma Şubesi" text,
    "Müşteri Kodu" text,
    "Müşteri Adı" text,
    "Müşteri Temsilcisi" text,
    "Sap Kodu" text,
    "Durum" text,
    "Kayıt Tarihi" date,
    "Müşteri Grubu" text,
    "Esk. Yakıt Başlangıç Tarihi" date,
    "Esk. Enf. Başlangıç Tarihi" date,
    "Ocak Desi" numeric default 0,
    "Şubat Desi" numeric default 0,
    "Mart Desi" numeric default 0,
    "Nisan Desi" numeric default 0,
    "Mayıs Desi" numeric default 0,
    "Haziran Desi" numeric default 0,
    "Temmuz Desi" numeric default 0,
    "Ağustos Desi" numeric default 0,
    "Eylül Desi" numeric default 0,
    "Ekim Desi" numeric default 0,
    "Kasım Desi" numeric default 0,
    "Aralık Desi" numeric default 0,
    "Gerçekleşen Toplam Desi" numeric default 0,
    "Tahmini Yıl Sonu Toplam Desi" numeric default 0,
    created_at timestamptz not null default now()
);

create index if not exists yil_kapanis_onceki_detay_revizyon_idx
    on public.yil_kapanis_onceki_detay_tablosu (revizyon_id);

grant select, insert, update, delete
    on public.yil_kapanis_onceki_detay_tablosu to anon, authenticated;
grant usage, select
    on sequence public.yil_kapanis_onceki_detay_tablosu_id_seq
    to anon, authenticated;

notify pgrst, 'reload schema';
